# WAP to print the odd numbers starting from 1 to 10

# First Method

i=1 

print("Print the odd numbers starting from 1 to 10:")
while i<=10:
    if i%2!=0:
        print(i,end=" ")
    i=i+1

# Second Method
j=1

print("\nPrint the odd numbers starting from 1 to 10:")
while j<=10:
    if j%2!=0:
        print(j,end=" ")
    j=j+2